import numpy as np
import matplotlib.pyplot as plt
from PIL import Image, ImageDraw

def display_bitmap_array(data, width, height, reverse_bits=True, inverted=True):
    """
    从C数组数据中创建并显示位图图像
    
    参数:
    data - 字节数组或整数列表(十六进制格式的C数组)
    width - 图像宽度(像素)
    height - 图像高度(像素)
    reverse_bits - 是否需要颠倒每个字节中的位(阴码/阳码)
    inverted - 是否反转颜色(0表示黑色或1表示黑色)
    """
    # 创建一个空白图像
    img = Image.new('1', (width, height), color=1 if inverted else 0)
    draw = ImageDraw.Draw(img)
    
    # 计算每行的字节数
    bytes_per_row = (width + 7) // 8
    
    # 遍历每一行
    for y in range(height):
        # 遍历每一行中的每个字节
        for x_byte in range(bytes_per_row):
            if y * bytes_per_row + x_byte >= len(data):
                continue
                
            byte = data[y * bytes_per_row + x_byte]
            
            # 处理每个字节中的8位
            for bit in range(8):
                # 计算像素位置
                x = x_byte * 8 + bit
                if x >= width:
                    continue
                
                # 提取位值(根据需要反转)
                if reverse_bits:
                    bit_value = (byte >> bit) & 1
                else:
                    bit_value = (byte >> (7 - bit)) & 1
                    
                # 设置像素颜色(可能需要反转颜色)
                if (bit_value == 1 and not inverted) or (bit_value == 0 and inverted):
                    draw.point((x, y), fill=0)
    
    # 显示图像
    plt.figure(figsize=(10, 10))
    plt.imshow(img, cmap='gray')
    plt.title(f'Bitmap Image ({width}x{height})')
    plt.axis('off')
    plt.show()
    
    return img

