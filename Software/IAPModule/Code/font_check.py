# 修改draw_char函数以支持不同字体
def draw_char(char, x_offset=0, y_offset=0, scale=1, canvas=None, font_type="normal"):
    """
    绘制单个字符
    
    参数:
    char - 要绘制的字符
    x_offset - x方向偏移
    y_offset - y方向偏移
    scale - 缩放比例
    canvas - 如果提供，将在此画布上绘制
    font_type - 字体类型，可选值："normal"或"elegant"
    
    返回:
    如果没有提供canvas，则返回包含字符的新画布
    """
    if canvas is None:
        canvas = np.zeros((8 * scale, 6 * scale), dtype=np.uint8)
    
    # 获取字符的字体数据
    char_code = ord(char) - 32  # ASCII码减去32得到字体数组索引
    
    # 根据字体类型选择字体数据
    if font_type == "elegant":
        font_data = elegant_font_6x8
    else:
        font_data = ascii_font_6x8
    
    if 0 <= char_code < len(font_data):
        char_data = font_data[char_code]
    else:
        # 如果字符不在范围内，使用空格
        char_data = font_data[0]
    
    # 绘制字符
    for col in range(6):
        byte_data = char_data[col]
        for row in range(8):
            # 检查位是否为1（逆向取模）
            if byte_data & (1 << row):
                # 在画布上绘制像素
                for i in range(scale):
                    for j in range(scale):
                        canvas_y = y_offset + row * scale + i
                        canvas_x = x_offset + col * scale + j
                        if 0 <= canvas_y < canvas.shape[0] and 0 <= canvas_x < canvas.shape[1]:
                            canvas[canvas_y, canvas_x] = 1
    
    return canvas

# 修改draw_string函数以支持不同字体
def draw_string(text, scale=1, spacing=1, font_type="normal"):
    """
    绘制字符串
    
    参数:
    text - 要绘制的字符串
    scale - 缩放比例
    spacing - 字符间距
    font_type - 字体类型，可选值："normal"或"elegant"
    
    返回:
    包含字符串的画布
    """
    if not text:
        return np.zeros((8 * scale, 1), dtype=np.uint8)
    
    # 计算画布大小
    width = len(text) * 6 * scale + (len(text) - 1) * spacing
    height = 8 * scale
    
    # 创建画布
    canvas = np.zeros((height, width), dtype=np.uint8)
    
    # 绘制每个字符
    for i, char in enumerate(text):
        x_offset = i * (6 * scale + spacing)
        draw_char(char, x_offset, 0, scale, canvas, font_type)
    
    return canvas

# 修改display_string函数以支持不同字体
def display_string(text, scale=3, spacing=1, fg_color='black', bg_color='white', font_type="normal"):
    """
    显示字符串
    
    参数:
    text - 要显示的字符串
    scale - 缩放比例
    spacing - 字符间距
    fg_color - 前景色
    bg_color - 背景色
    font_type - 字体类型，可选值："normal"或"elegant"
    """
    canvas = draw_string(text, scale, spacing, font_type)
    
    # 创建颜色映射
    cmap = ListedColormap([bg_color, fg_color])
    
    # 显示图像
    plt.figure(figsize=(len(text) * 0.6, 1))
    plt.imshow(canvas, cmap=cmap, interpolation='nearest')
    plt.axis('off')
    plt.title(f'字符串: "{text}" (字体: {font_type})')
    plt.tight_layout()
    plt.show()

